"""
Pydantic models for Granite recommendation (Agent 8 output).
"""
from __future__ import annotations
from pydantic import BaseModel, Field


class RecommendationReason(BaseModel):
    point: str
    metric: str = ""
    value: str = ""


class GroundingFlag(BaseModel):
    """Records whether a metric value cited by Granite matches the computed value."""
    metric: str
    cited_value: str
    computed_value: str | None = None
    match: bool = False
    tolerance_pct: float = 10.0  # acceptable %-difference


class RecommendationResult(BaseModel):
    ticker: str
    recommendation: str            # Overweight | Hold | Underweight
    confidence: float = Field(ge=0.0, le=1.0)
    target_horizon: str = "12 months"
    reasons: list[RecommendationReason] = Field(default_factory=list)
    key_risks: list[str] = Field(default_factory=list)
    forward_outlook: str = ""
    metrics_cited: dict[str, float | str | None] = Field(default_factory=dict)
    grounding_flags: list[GroundingFlag] = Field(default_factory=list)
    granite_mode: str = "demo"     # "live" | "demo" | "fallback"
    disclaimer: str = (
        "This output is generated by an AI model and is NOT financial advice. "
        "Always consult a licensed financial advisor before making investment decisions."
    )
