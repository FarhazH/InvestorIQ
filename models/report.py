"""
Pydantic models for the final assembled report (Agent 9 output).
"""
from __future__ import annotations
from typing import Any
from pydantic import BaseModel, Field


class FinalReport(BaseModel):
    run_id: str
    ticker: str
    competitors: list[str] = Field(default_factory=list)
    generated_at: str = ""
    # All agent outputs embedded
    kpis: dict[str, Any] = Field(default_factory=dict)
    ratios: dict[str, Any] = Field(default_factory=dict)
    benchmark: dict[str, Any] = Field(default_factory=dict)
    sentiment: dict[str, Any] = Field(default_factory=dict)
    risk: dict[str, Any] = Field(default_factory=dict)
    recommendation: dict[str, Any] = Field(default_factory=dict)
    quality_report: dict[str, Any] = Field(default_factory=dict)
    # Export paths
    json_path: str = ""
    pdf_path: str = ""
    cos_key: str = ""
    disclaimer: str = (
        "This report is generated by an AI-powered system and is NOT financial advice. "
        "Always consult a licensed financial advisor before making investment decisions."
    )
