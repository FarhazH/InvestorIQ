"""
Pydantic models for Phase 3 RAG (Retrieval-Augmented Generation) over SEC filings.
"""
from __future__ import annotations
from pydantic import BaseModel, Field


class FilingChunk(BaseModel):
    """A single text chunk extracted from a filing document."""
    chunk_id: str
    ticker: str
    filing_type: str                    # "10-K" | "10-Q" | "earnings"
    filing_date: str
    section: str                        # e.g. "Risk Factors", "MD&A"
    text: str
    source_url: str = ""
    page_num: int | None = None


class RAGDocument(BaseModel):
    """Represents an ingested filing document with its chunks."""
    ticker: str
    filing_type: str
    filing_date: str
    source_url: str = ""
    total_chars: int = 0
    n_chunks: int = 0
    sections_found: list[str] = Field(default_factory=list)


class RetrievedChunk(BaseModel):
    """A chunk returned by the vector store retrieval."""
    chunk_id: str
    ticker: str
    filing_type: str
    filing_date: str
    section: str
    text: str
    score: float                        # similarity score 0–1
    source_url: str = ""


class AnalystAnswer(BaseModel):
    """Answer produced by Granite RAG over filing chunks."""
    question: str
    answer: str
    sources: list[RetrievedChunk] = Field(default_factory=list)
    ticker: str
    granite_mode: str = "demo"
    disclaimer: str = (
        "This answer is generated by an AI model using SEC filing excerpts. "
        "It is NOT financial advice and may contain errors. "
        "Always verify with the original filing documents."
    )


class RiskFactorSummary(BaseModel):
    """Extracted risk factors and management outlook from filings."""
    ticker: str
    filing_type: str
    filing_date: str
    risk_factors: list[str] = Field(default_factory=list)
    management_outlook: str = ""
    key_themes: list[str] = Field(default_factory=list)
    granite_mode: str = "demo"


class RAGResult(BaseModel):
    """Full RAG pipeline output stored in PipelineState."""
    ticker: str
    documents: list[RAGDocument] = Field(default_factory=list)
    risk_summary: RiskFactorSummary | None = None
    index_built: bool = False
    index_path: str = ""
    n_total_chunks: int = 0
    error: str = ""
